#!/usr/bin/env bash
# Safe Sway/SwayFX integration for ModernDock.
#
#   sway-integration.sh status             show what is configured
#   sway-integration.sh enable-autostart   start the dock with Sway
#   sway-integration.sh disable-autostart  remove exactly what enable added
#   sway-integration.sh check-blur         probe whether this compositor is SwayFX
#
# How it stays safe:
#   * your Sway config is only ever changed by adding ONE marked `include` block;
#   * a timestamped backup is made before any change;
#   * the result is validated with `sway --validate` (when available) and the
#     backup is restored automatically if validation fails;
#   * `disable-autostart` removes only the marked block.
# All real settings live in ~/.config/moderndock/sway.conf, which this script owns.
set -euo pipefail

ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
CONF_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
SNIPPET="$CONF_HOME/moderndock/sway.conf"
BEGIN="# >>> moderndock (managed by ModernDock/scripts/sway-integration.sh; do not edit) >>>"
END="# <<< moderndock <<<"

find_sway_config() {
    if [ -n "${MODERNDOCK_SWAY_CONFIG:-}" ]; then printf '%s\n' "$MODERNDOCK_SWAY_CONFIG"; return; fi
    local c
    for c in "$CONF_HOME/sway/config" "$HOME/.sway/config"; do
        if [ -f "$c" ]; then printf '%s\n' "$c"; return; fi
    done
}

has_block() { grep -qF "$BEGIN" "$1" 2>/dev/null; }

SWAY_ERR=""
validate() {
    # 0 = config validates (or there is no sway to ask); 1 = sway rejects it.
    # Sway's complaint is kept in SWAY_ERR.
    command -v sway >/dev/null 2>&1 || return 0
    local rt="${XDG_RUNTIME_DIR:-}" tmp=""
    if [ -z "$rt" ] || [ ! -d "$rt" ]; then tmp="$(mktemp -d)"; rt="$tmp"; fi
    local out rc=0
    out="$(XDG_RUNTIME_DIR="$rt" sway --validate --config "$1" 2>&1)" || rc=$?
    [ -n "$tmp" ] && rm -rf "$tmp"
    SWAY_ERR="$out"
    return "$rc"
}

# Did our change break a config that was valid before? Only then is it our fault.
broke_config() {  # $1 = original (backup), $2 = modified
    if validate "$2"; then return 1; fi
    local err="$SWAY_ERR"
    if validate "$1"; then SWAY_ERR="$err"; return 0; fi
    echo "Note: your original Sway config does not validate either; skipping the safety check." >&2
    return 1
}

write_snippet() {
    mkdir -p "$(dirname "$SNIPPET")"
    cat >"$SNIPPET" <<EOF
# Generated by ModernDock/scripts/sway-integration.sh (safe to regenerate).
# Start the dock with Sway. A second copy refuses to start, so reloads are harmless.
exec "$ROOT/bin/moderndock"
# After "swaymsg reload", ask the dock to re-apply its SwayFX blur rule.
exec_always sleep 1 && "$ROOT/bin/moderndock-ctl" reload

# Optional keybindings (remove the leading # to use; \$mod must exist in your config):
# bindsym \$mod+Ctrl+d exec "$ROOT/bin/moderndock-ctl" toggle
# bindsym \$mod+Ctrl+1 exec "$ROOT/bin/moderndock-ctl" launch 1
EOF
}

cmd_status() {
    local cfg; cfg="$(find_sway_config || true)"
    echo "ModernDock directory : $ROOT"
    echo "Sway config          : ${cfg:-<none found>}"
    if [ -n "$cfg" ] && has_block "$cfg"; then
        echo "Autostart            : ENABLED (include block present)"
    else
        echo "Autostart            : disabled"
    fi
    [ -f "$SNIPPET" ] && echo "Snippet              : $SNIPPET" || true
}

cmd_enable() {
    local cfg create=0
    [ "${1:-}" = "--create-config" ] && create=1
    cfg="$(find_sway_config || true)"
    if [ -z "$cfg" ]; then
        if [ "$create" = 1 ] && [ -f /etc/sway/config ]; then
            cfg="$CONF_HOME/sway/config"
            mkdir -p "$(dirname "$cfg")"
            printf '# Created by ModernDock: keeps the system defaults.\ninclude /etc/sway/config\n' >"$cfg"
            echo "Created $cfg (includes /etc/sway/config)."
        else
            echo "No user Sway config found ($CONF_HOME/sway/config)." >&2
            echo "Either create one, or re-run with:  $0 enable-autostart --create-config" >&2
            echo "(that creates a config which just includes /etc/sway/config)." >&2
            return 1
        fi
    fi
    if has_block "$cfg"; then
        write_snippet
        echo "Autostart already enabled; snippet refreshed."
        return 0
    fi
    write_snippet
    local backup; backup="$cfg.moderndock-backup-$(date +%Y%m%d-%H%M%S)"
    cp -p -- "$cfg" "$backup"
    # make sure the file ends with a newline so our block starts on its own line
    if [ -s "$cfg" ] && [ -n "$(tail -c1 "$cfg")" ]; then printf '\n' >>"$cfg"; fi
    {
        printf '%s\n' "$BEGIN"
        printf 'include %s\n' "$SNIPPET"
        printf '%s\n' "$END"
    } >>"$cfg"
    if broke_config "$backup" "$cfg"; then
        cp -p -- "$backup" "$cfg"
        echo "Sway rejected the modified config; restored your original ($backup kept)." >&2
        [ -n "$SWAY_ERR" ] && echo "$SWAY_ERR" >&2
        return 1
    fi
    echo "Autostart enabled."
    echo "  Backup of your config : $backup"
    echo "  Settings snippet      : $SNIPPET"
    echo "Takes effect at next login, or now with:  swaymsg reload"
}

cmd_disable() {
    local cfg; cfg="$(find_sway_config || true)"
    if [ -z "$cfg" ] || ! has_block "$cfg"; then
        echo "Autostart was not enabled."
    else
        local backup tmp
        backup="$cfg.moderndock-backup-$(date +%Y%m%d-%H%M%S)"
        cp -p -- "$cfg" "$backup"
        tmp="$(mktemp)"
        awk -v b="$BEGIN" -v e="$END" '
            $0 == b { skip = 1; next }
            skip && $0 == e { skip = 0; next }
            !skip { print }' "$cfg" >"$tmp"
        cat "$tmp" >"$cfg"
        rm -f "$tmp"
        if broke_config "$backup" "$cfg"; then
            cp -p -- "$backup" "$cfg"
            echo "Sway rejected the edited config; restored it ($backup kept)." >&2
            [ -n "$SWAY_ERR" ] && echo "$SWAY_ERR" >&2
            return 1
        fi
        echo "Autostart disabled (backup: $backup)."
    fi
    rm -f "$SNIPPET"
}

cmd_check_blur() {
    if ! command -v swaymsg >/dev/null 2>&1 || [ -z "${SWAYSOCK:-}" ]; then
        echo "Not inside a running Sway session (swaymsg/SWAYSOCK unavailable); cannot probe."
        return 2
    fi
    if swaymsg -t get_version 2>/dev/null | grep -qi swayfx; then
        echo "Version string mentions SwayFX."
    fi
    # `layer_effects` only exists in SwayFX; the probe disables blur for a namespace nobody uses.
    if swaymsg -r 'layer_effects "moderndock-probe" "blur disable"' 2>/dev/null | grep -q '"success": *true'; then
        echo "SwayFX detected: ModernDock's 'Background blur' option will work."
    else
        echo "layer_effects is not available: this looks like plain Sway."
        echo "ModernDock will still work, with translucency but no blur."
        return 1
    fi
}

case "${1:-status}" in
    status) cmd_status ;;
    enable-autostart|enable) shift || true; cmd_enable "${1:-}" ;;
    disable-autostart|disable) cmd_disable ;;
    check-blur) cmd_check_blur ;;
    -h|--help|help) sed -n '2,15p' "${BASH_SOURCE[0]}" ;;
    *) echo "unknown command: $1 (try --help)" >&2; exit 2 ;;
esac
